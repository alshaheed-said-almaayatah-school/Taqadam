/**
 * app.js يستخدم findLesson(lessonId) التي ترجع {subject, unit, lesson}
 * حيث subject.id نصي، و lesson.id = "X-Y-Z"
 */
function findLessonById(lessonId) {
    if (!lessonId) return null;
    for (const s of SUBJECTS) {
        for (const u of s.units) {
            for (const l of u.lessons) {
                if (l.id === lessonId) return { subject: s, unit: u, lesson: l };
            }
        }
    }
    return null;
}

/**
 * أسئلة درس معين (متوافق مع المفتاح النصي "X-Y-Z")
 */
function getLessonQuestions(lessonId) {
    return QUESTIONS[lessonId] || [];
}

